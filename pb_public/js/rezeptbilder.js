/* pinn. – Recipe images (js/rezeptbilder.js)
   Part of the app code that used to be a single block in index.html. Classic script, no build step:
   it is loaded right after the inline script of index.html and before the other files in js/
   (the load order is listed at the bottom of index.html and in pinn-setup.sh).
   Contents: recipe images as separate files in the "rezept_bilder" collection (RECIPE_IMAGE_*, recipeImageSrc,
   compressImageDataUrl, uploadRecipeImage, deleteRecipeImageRecord, migrateEmbeddedRecipeImages) and the image crop
   (RECIPE_FRAME_MAX_ZOOM, normRecipeImageFrame, recipeImageFrameCss, recipeImgStyleAttr, applyRecipeImageFrame).
   The crop editor in the recipe dialog is in js/rezeptbild.js. */

/* ---------- Recipe images: shrink them and store them as separate files in PocketBase ----------
   Images are NO LONGER stored as huge text in the family data record, but as a file in the
   "rezept_bilder" collection. The recipe only keeps the short path (r.image) and the record ID
   (r.imageRecordId, for deleting). The path is relative on purpose, so a port change breaks nothing.
   Old recipes with an embedded image (data:...) are moved automatically on start. */
const RECIPE_IMAGE_COLLECTION = 'rezept_bilder';
const RECIPE_IMAGE_MAX_PX = 1600;
const RECIPE_IMAGE_QUALITY = 0.8;

// For small displays (list, slider, search) load the thumbnail generated by PocketBase instead of the
// whole image. Embedded legacy images (data:...) are returned unchanged.
// With frame (image crop of a recipe, see normRecipeImageFrame) and a moved crop the uncropped
// thumbnail (600x600f) is loaded - the square 400x400 one crops to the centre and would distort
// the chosen crop.
function recipeImageSrc(image, thumb, frame) {
  if (!image) return '';
  if (thumb && image.startsWith('/api/files/')) {
    const f = normRecipeImageFrame(frame);
    return image + (f && (f.x !== 50 || f.y !== 50) ? '?thumb=600x600f' : '?thumb=400x400');
  }
  return image;
}

/* ---------- Image crop (move/zoom) ----------
   r.imageFrame = { x, y, z }: x/y = crop position in percent (0 = left/top edge,
   100 = right/bottom edge), z = zoom (1 = frame just filled, up to 4). The image always fills the
   frame completely (object-fit: cover), only enlarged and moved - entirely without transform,
   so rounded corners clip cleanly everywhere (Safari included). The frame around the image
   needs position: relative for this. Centre without zoom = no crop stored. */
const RECIPE_FRAME_MAX_ZOOM = 4;
function normRecipeImageFrame(f) {
  if (!f || typeof f !== 'object') return null;
  const num = (v, d) => { const n = Number(v); return isFinite(n) ? n : d; };
  const x = Math.round(Math.min(100, Math.max(0, num(f.x, 50))) * 10) / 10;
  const y = Math.round(Math.min(100, Math.max(0, num(f.y, 50))) * 10) / 10;
  const z = Math.round(Math.min(RECIPE_FRAME_MAX_ZOOM, Math.max(1, num(f.z, 1))) * 100) / 100;
  if (x === 50 && y === 50 && z === 1) return null;
  return { x, y, z };
}
function recipeImageFrameCss(frame) {
  const f = normRecipeImageFrame(frame);
  if (!f) return '';
  const k = f.z - 1;
  const size = (f.z * 100).toFixed(2);
  return `position:absolute;left:${(-k * f.x).toFixed(2)}%;top:${(-k * f.y).toFixed(2)}%;width:${size}%;height:${size}%;max-width:none;max-height:none;object-fit:cover;object-position:${f.x}% ${f.y}%;`;
}
// Ready-made style attribute for image HTML in templates (empty if no crop is set)
function recipeImgStyleAttr(r) {
  const css = recipeImageFrameCss(r && r.imageFrame);
  return css ? ` style="${css}"` : '';
}
function applyRecipeImageFrame(img, frame) {
  if (img) img.style.cssText = recipeImageFrameCss(frame);
}

// Shrinks an image (data URL) to at most RECIPE_IMAGE_MAX_PX on the longer side and returns
// it as a JPEG blob.
function compressImageDataUrl(dataUrl) {
  return new Promise((resolve, reject) => {
    const img = new Image();
    img.onload = () => {
      const scale = Math.min(1, RECIPE_IMAGE_MAX_PX / Math.max(img.width, img.height));
      const canvas = document.createElement('canvas');
      canvas.width = Math.round(img.width * scale);
      canvas.height = Math.round(img.height * scale);
      const ctx = canvas.getContext('2d');
      ctx.fillStyle = '#ffffff'; // transparent PNGs would otherwise turn black in the JPEG
      ctx.fillRect(0, 0, canvas.width, canvas.height);
      ctx.drawImage(img, 0, 0, canvas.width, canvas.height);
      canvas.toBlob(blob => blob ? resolve(blob) : reject(new Error(tk('recipe.imageConvertFailed'))), 'image/jpeg', RECIPE_IMAGE_QUALITY);
    };
    img.onerror = () => reject(new Error(tk('recipe.imageUnreadable')));
    img.src = dataUrl;
  });
}

// Shrinks and uploads an image. Returns { path, recordId }.
async function uploadRecipeImage(dataUrl) {
  const blob = await compressImageDataUrl(dataUrl);
  const form = new FormData();
  form.append('bild', blob, 'rezept.jpg');
  form.append('familie', (currentUser() && currentUser().familie) || '');
  const rec = await pb.collection(RECIPE_IMAGE_COLLECTION).create(form);
  return { path: `/api/files/${RECIPE_IMAGE_COLLECTION}/${rec.id}/${rec.bild}`, recordId: rec.id };
}

function deleteRecipeImageRecord(recordId) {
  if (!recordId) return;
  pb.collection(RECIPE_IMAGE_COLLECTION).delete(recordId).catch(err => console.warn('Could not delete the recipe image:', err));
}

// One-time move: upload embedded legacy images and replace them in the recipe by the path. Runs in the
// background after the start. If the collection is still missing, everything stays as it is (the next start
// tries again).
let recipeImageMigrationRunning = false;
async function migrateEmbeddedRecipeImages() {
  if (recipeImageMigrationRunning) return;
  const pending = recipes.filter(r => typeof r.image === 'string' && r.image.startsWith('data:'));
  if (!pending.length) return;
  recipeImageMigrationRunning = true;
  let moved = 0;
  try {
    for (const r of pending) {
      try {
        const { path, recordId } = await uploadRecipeImage(r.image);
        r.image = path;
        r.imageRecordId = recordId;
        moved++;
      } catch (err) {
        console.warn('Image move stopped (does the collection "' + RECIPE_IMAGE_COLLECTION + '" exist?):', err);
        break;
      }
    }
    if (moved) {
      await persistState();
      console.log(`Image move: ${moved} of ${pending.length} recipe images moved out.`);
      renderRecipesForCurrentView();
    }
  } finally {
    recipeImageMigrationRunning = false;
  }
}

